#include <stdio.h>

int main()
{
    int a, b, sum;
    // Taking input from user
    printf("Enter the first number = ");
    scanf("%d", &a);

    printf("Enter the second number = ");
    scanf("%d", &b);

    // addition of the two numbers
    sum = (a + b);
    
    printf("The sum is %d", sum);


    return 0;
}